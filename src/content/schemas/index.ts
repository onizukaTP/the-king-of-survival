import { z } from 'zod';

const slug = (prefix: string) => z.string().regex(new RegExp(String.raw`^${prefix}\.[a-z0-9_]+$`), `must look like ${prefix}.some_slug`);
const assetId = z.string().min(1);
const lat = z.number().min(-90).max(90);
const lon = z.number().min(-180).max(180);

export const characterSchema = z.object({
  id: slug('character'),
  name: z.string().min(1),
  age: z.number().int().nonnegative(),
  portrait: assetId,
});

export const siteKinds = ['home', 'hunting', 'ruins', 'rail', 'road', 'water', 'city'] as const;

export const siteSchema = z.object({
  id: slug('loc'),
  name: z.string().min(1),
  kind: z.enum(siteKinds),
  lat,
  lon,
  knownAtStart: z.boolean(),
});

export const worldSchema = z.object({
  roadSpeedKmh: z.number().positive(),
  crossCountrySpeedKmh: z.number().positive(),
  sightRadiusKm: z.number().positive(),
  legMaxMinutes: z.number().int().positive(),
});

// Generated by scripts/geo/build-geo.mjs. Nodes are [lat, lon]; edges are [nodeA, nodeB, lengthKm].
export const roadsSchema = z.object({
  nodes: z.array(z.tuple([lat, lon])),
  edges: z.array(z.tuple([z.number().int().nonnegative(), z.number().int().nonnegative(), z.number().nonnegative()])),
});

// Generated by scripts/geo/build-geo.mjs. GeoJSON-style MultiPolygon coordinates: [lon, lat].
export const outlineSchema = z.object({
  polygons: z.array(z.array(z.array(z.tuple([lon, lat])).min(4)).min(1)).min(1),
});

export const itemCategories = ['food', 'water', 'medical', 'material', 'weapon', 'tool'] as const;

export const itemSchema = z.object({
  id: slug('item'),
  name: z.string().min(1),
  category: z.enum(itemCategories),
  weightKg: z.number().nonnegative(),
  // Applied to the survival meters when used (eaten, drunk, applied).
  effects: z.object({ food: z.number(), water: z.number(), health: z.number() }).partial().optional(),
  curesInjury: z.boolean().optional(),
  // Chance (0–1) that using it makes Prabu ill (D-027).
  illnessChance: z.number().min(0).max(1).optional(),
  // What is left after use, e.g. the empty bottle.
  leaves: slug('item').optional(),
  spoilsAfterMinutes: z.number().int().positive().optional(),
  weapon: z.boolean().optional(),
  // Items that run down: lighter lights, torch battery.
  charge: z.object({ max: z.number().int().positive(), unit: z.enum(['count', 'percent']) }).optional(),
  // Using this item refills another item's charge.
  recharges: z.object({ itemId: slug('item'), amount: z.number().int().positive(), minutes: z.number().int().nonnegative(), consumed: z.boolean() }).optional(),
  // A tool that must be in the pack to use this item, e.g. the can opener for tinned food (D-056).
  needsItem: slug('item').optional(),
});

const meters = z.object({ health: z.number(), food: z.number(), water: z.number(), rest: z.number() });

// D-023, D-035, D-036, D-027.
export const survivalSchema = z.object({
  start: meters,
  drainPerHour: z.object({ food: z.number().nonnegative(), water: z.number().nonnegative(), rest: z.number().nonnegative() }),
  sleepRestPerHour: z.number().positive(),
  exhaustedDrainMultiplier: z.number().min(1),
  emptyMeterHealthPerHour: z.number().nonnegative(),
  sleepHealthPerHour: z.number().nonnegative(),
  sleepHealAbove: z.number(),
  warnAt: z.number(),
  carry: z.object({ freeKg: z.number().positive(), maxKg: z.number().positive(), multiplierAtMax: z.number().min(1) }),
  illness: z.object({ minutes: z.number().int().positive(), waterDrainMultiplier: z.number().min(1) }),
});

export const newGameSchema = z.object({
  startingCharacter: slug('character'),
  startSite: slug('loc'),
  startClockMinutes: z.number().int().nonnegative(),
  startingWeapon: slug('item').nullable(),
  startingKit: z.array(z.object({ itemId: slug('item'), count: z.number().int().positive(), charge: z.number().int().nonnegative().optional() })),
});

const lootEntry = z.object({
  itemId: slug('item'), chance: z.number().min(0).max(1), min: z.number().int().positive(), max: z.number().int().positive(),
  // Charge it's found with, rolled between the two (e.g. a matchbox with 3–10 matches); full if absent.
  charge: z.tuple([z.number().int().nonnegative(), z.number().int().nonnegative()]).optional(),
});

// Per-site loot (P-013, D-033). Search: each draw takes the first entry that hits. Hunt: every entry rolls.
export const lootSchema = z.object({
  siteId: slug('loc'),
  search: z.array(lootEntry),
  hunt: z.array(lootEntry).optional(),
});

const place = z.object({ name: z.string(), lat, lon });

// Scavenging, water and radiation numbers (P-013, D-043 to D-045).
export const scavengingSchema = z.object({
  searchMinutes: z.number().int().positive(),
  torchSearchMinutes: z.number().int().positive(),
  torchItemId: slug('item'),
  torchChargePerSearch: z.number().int().positive(),
  drawsPerSearch: z.number().int().positive(),
  depletionPerSearch: z.number().min(0).max(100),
  minRichness: z.number().min(0).max(100),
  refreshMinutes: z.number().int().positive(),
  huntMinutes: z.number().int().positive(),
  groundMinutes: z.number().int().positive(),
  waterRangeKm: z.number().nonnegative(),
  fillMinutesPerBottle: z.number().int().nonnegative(),
  drinkMinutes: z.number().int().nonnegative(),
  bottles: z.object({ empty: slug('item'), clean: slug('item'), unsafe: slug('item') }),
  radiation: z.object({ from: place, to: place, radiusKm: z.number().positive(), chancePerHour: z.number().min(0).max(1), amount: z.number().positive() }),
});

// Fire and cooking (D-056, P-016).
export const fireSchema = z.object({
  firewoodItemId: slug('item'),
  burnMinutesPerFirewood: z.number().int().positive(),
  // Ways to light a fire; itemId null needs nothing (rubbing two sticks).
  methods: z.array(z.object({
    id: z.string().min(1), name: z.string().min(1), itemId: slug('item').nullable(),
    chargePerFire: z.number().int().nonnegative(), minutes: z.number().int().positive(),
  })).min(1),
  // Bottles that count as "a bottle of water" for recipes that use one; the first is used first.
  waterItemIds: z.array(slug('item')).min(1),
  // Each turns up to maxBatch of `from` into as many `to` over a burning fire.
  recipes: z.array(z.object({
    id: slug('recipe'), name: z.string().min(1), from: slug('item'), to: slug('item'),
    maxBatch: z.number().int().positive(), minutes: z.number().int().positive(),
    tool: slug('item').nullable(), usesWater: z.boolean(),
  })).min(1),
});

// Generated by scripts/geo/build-water.mjs. Coordinates are [lon, lat]. `river` marks flowing (clean) water.
export const waterSchema = z.object({
  areas: z.array(z.object({ river: z.boolean(), ring: z.array(z.tuple([lon, lat])).min(4) })),
  rivers: z.array(z.array(z.tuple([lon, lat])).min(2)),
  // Mapped wells: clean water (D-050).
  wells: z.array(z.tuple([lon, lat])),
});

// A kind of building on a town map, with its own search time, stock loss and loot (D-049, P-014).
export const buildingTypeSchema = z.object({
  id: slug('btype'),
  name: z.string().min(1),
  searchMinutes: z.number().int().positive(),
  torchSearchMinutes: z.number().int().positive(),
  depletionPerSearch: z.number().min(0).max(100),
  search: z.array(lootEntry).min(1),
});

// A town's map (D-049): buildings and water placed at real coordinates. The town's site point is its edge.
export const townSchema = z.object({
  siteId: slug('loc'),
  buildings: z.array(z.object({ id: slug('building'), typeId: slug('btype'), name: z.string().min(1), lat, lon })).min(1),
  // A well gives clean water, a tank unsafe water (D-044, D-050).
  water: z.array(z.object({ id: slug('waterpoint'), kind: z.enum(['well', 'tank']), name: z.string().min(1), lat, lon })),
  // Ways out besides the edge (D-054): leaving from one puts Prabu at that spot on the world map.
  ends: z.array(z.object({ id: slug('end'), name: z.string().min(1), lat, lon })),
});

// Generated by scripts/geo/build-town-streets.mjs: street lines per town, [lon, lat]; drawn only.
export const townStreetsSchema = z.record(z.string(), z.array(z.array(z.tuple([lon, lat])).min(2)));

export type Character = z.infer<typeof characterSchema>;
export type Site = z.infer<typeof siteSchema>;
export type SiteKind = Site['kind'];
export type WorldConfig = z.infer<typeof worldSchema>;
export type Roads = z.infer<typeof roadsSchema>;
export type Outline = z.infer<typeof outlineSchema>;
export type Loot = z.infer<typeof lootSchema>;
export type LootEntry = z.infer<typeof lootEntry>;
export type ScavengingConfig = z.infer<typeof scavengingSchema>;
export type Water = z.infer<typeof waterSchema>;
export type BuildingType = z.infer<typeof buildingTypeSchema>;
export type Town = z.infer<typeof townSchema>;
export type FireConfig = z.infer<typeof fireSchema>;
export type TownStreets = z.infer<typeof townStreetsSchema>;
export type Item = z.infer<typeof itemSchema>;
export type ItemCategory = Item['category'];
export type SurvivalConfig = z.infer<typeof survivalSchema>;
export type NewGameConfig = z.infer<typeof newGameSchema>;
