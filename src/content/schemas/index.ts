import { z } from 'zod';

const slug = (prefix: string) => z.string().regex(new RegExp(String.raw`^${prefix}\.[a-z0-9_]+$`), `must look like ${prefix}.some_slug`);
const assetId = z.string().min(1);
const lat = z.number().min(-90).max(90);
const lon = z.number().min(-180).max(180);

// Fighting and luck stats (D-065, D-066). Percentages are whole numbers (crit rate 5 = 5%).
export const statsSchema = z.object({
  atk: z.number(), def: z.number(), spd: z.number(), critRate: z.number(), critDamage: z.number(),
  acc: z.number(), dodge: z.number(), hunting: z.number(), luck: z.number(),
});
export const bands = ['close', 'mid', 'far'] as const;

export const characterSchema = z.object({
  id: slug('character'),
  name: z.string().min(1),
  age: z.number().int().nonnegative(),
  portrait: assetId,
  stats: statsSchema,
});

// How a weapon fights (D-063, D-066): damage roll, the farthest band it reaches, and what it adds to the stats.
const weaponProfile = z.object({
  damage: z.tuple([z.number().int().nonnegative(), z.number().int().nonnegative()]),
  reach: z.enum(bands),
  // Uses one of this item a shot (arrows).
  ammo: z.string().optional(),
  // ACC change when the target is Close (the bow).
  accAtClose: z.number().optional(),
  bonus: statsSchema.partial().optional(),
});

export const siteKinds = ['home', 'hunting', 'ruins', 'rail', 'road', 'water', 'city'] as const;

export const siteSchema = z.object({
  id: slug('loc'),
  name: z.string().min(1),
  kind: z.enum(siteKinds),
  lat,
  lon,
  knownAtStart: z.boolean(),
});

export const worldSchema = z.object({
  roadSpeedKmh: z.number().positive(),
  crossCountrySpeedKmh: z.number().positive(),
  sightRadiusKm: z.number().positive(),
  legMaxMinutes: z.number().int().positive(),
  // Night and the moon (D-048, D-060): minutes of the day, and which days of the cycle have a full-moon night.
  night: z.object({
    startMinute: z.number().int().min(0).max(1439),
    endMinute: z.number().int().min(0).max(1439),
    moonCycleDays: z.number().int().positive(),
    fullMoonDays: z.array(z.number().int().positive()),
    torchChargePerHour: z.number().positive(),
  }),
});

// Generated by scripts/geo/build-geo.mjs. Nodes are [lat, lon]; edges are [nodeA, nodeB, lengthKm].
export const roadsSchema = z.object({
  nodes: z.array(z.tuple([lat, lon])),
  edges: z.array(z.tuple([z.number().int().nonnegative(), z.number().int().nonnegative(), z.number().nonnegative()])),
});

// Generated by scripts/geo/build-geo.mjs. GeoJSON-style MultiPolygon coordinates: [lon, lat].
export const outlineSchema = z.object({
  polygons: z.array(z.array(z.array(z.tuple([lon, lat])).min(4)).min(1)).min(1),
});

export const itemCategories = ['food', 'water', 'medical', 'material', 'weapon', 'tool'] as const;

export const itemSchema = z.object({
  id: slug('item'),
  name: z.string().min(1),
  category: z.enum(itemCategories),
  weightKg: z.number().nonnegative(),
  // Applied to the survival meters when used (eaten, drunk, applied).
  effects: z.object({ food: z.number(), water: z.number(), health: z.number() }).partial().optional(),
  curesInjury: z.boolean().optional(),
  // Chance (0–1) that using it makes Prabu ill (D-027).
  illnessChance: z.number().min(0).max(1).optional(),
  // What is left after use, e.g. the empty bottle.
  leaves: slug('item').optional(),
  spoilsAfterMinutes: z.number().int().positive().optional(),
  weapon: z.boolean().optional(),
  // Items that run down: lighter lights, torch battery.
  charge: z.object({ max: z.number().int().positive(), unit: z.enum(['count', 'percent']) }).optional(),
  // Using this item refills another item's charge.
  recharges: z.object({ itemId: slug('item'), amount: z.number().int().positive(), minutes: z.number().int().nonnegative(), consumed: z.boolean() }).optional(),
  // A tool that must be in the pack to use this item, e.g. the can opener for tinned food (D-056).
  needsItem: slug('item').optional(),
  combat: weaponProfile.optional(),
});

const meters = z.object({ health: z.number(), food: z.number(), water: z.number(), rest: z.number() });

// D-023, D-035, D-036, D-027.
export const survivalSchema = z.object({
  start: meters,
  drainPerHour: z.object({ food: z.number().nonnegative(), water: z.number().nonnegative(), rest: z.number().nonnegative() }),
  sleepRestPerHour: z.number().positive(),
  exhaustedDrainMultiplier: z.number().min(1),
  emptyMeterHealthPerHour: z.number().nonnegative(),
  sleepHealthPerHour: z.number().nonnegative(),
  sleepHealAbove: z.number(),
  warnAt: z.number(),
  carry: z.object({ freeKg: z.number().positive(), maxKg: z.number().positive(), multiplierAtMax: z.number().min(1) }),
  illness: z.object({ minutes: z.number().int().positive(), waterDrainMultiplier: z.number().min(1) }),
  // D-061: sleeping to full Rest at home or beside a fire gives this condition.
  shelteredSleepCondition: slug('condition'),
});

export const newGameSchema = z.object({
  startingCharacter: slug('character'),
  startSite: slug('loc'),
  startClockMinutes: z.number().int().nonnegative(),
  startingWeapon: slug('item').nullable(),
  startingKit: z.array(z.object({ itemId: slug('item'), count: z.number().int().positive(), charge: z.number().int().nonnegative().optional() })),
});

const lootEntry = z.object({
  itemId: slug('item'), chance: z.number().min(0).max(1), min: z.number().int().positive(), max: z.number().int().positive(),
  // Charge it's found with, rolled between the two (e.g. a matchbox with 3–10 matches); full if absent.
  charge: z.tuple([z.number().int().nonnegative(), z.number().int().nonnegative()]).optional(),
});

// Per-site loot (P-013, D-033). Search: each draw takes the first entry that hits. Hunt: every entry rolls.
export const lootSchema = z.object({
  siteId: slug('loc'),
  search: z.array(lootEntry),
  hunt: z.array(lootEntry).optional(),
});

const place = z.object({ name: z.string(), lat, lon });

// Scavenging, water and radiation numbers (P-013, D-043 to D-045).
export const scavengingSchema = z.object({
  searchMinutes: z.number().int().positive(),
  torchSearchMinutes: z.number().int().positive(),
  torchItemId: slug('item'),
  torchChargePerSearch: z.number().int().positive(),
  drawsPerSearch: z.number().int().positive(),
  depletionPerSearch: z.number().min(0).max(100),
  minRichness: z.number().min(0).max(100),
  refreshMinutes: z.number().int().positive(),
  huntMinutes: z.number().int().positive(),
  groundMinutes: z.number().int().positive(),
  waterRangeKm: z.number().nonnegative(),
  fillMinutesPerBottle: z.number().int().nonnegative(),
  drinkMinutes: z.number().int().nonnegative(),
  bottles: z.object({ empty: slug('item'), clean: slug('item'), unsafe: slug('item') }),
  radiation: z.object({ from: place, to: place, radiusKm: z.number().positive(), chancePerHour: z.number().min(0).max(1), amount: z.number().positive() }),
});

// Fire and cooking (D-056, P-016).
export const fireSchema = z.object({
  firewoodItemId: slug('item'),
  burnMinutesPerFirewood: z.number().int().positive(),
  // Ways to light a fire; itemId null needs nothing (rubbing two sticks).
  methods: z.array(z.object({
    id: z.string().min(1), name: z.string().min(1), itemId: slug('item').nullable(),
    chargePerFire: z.number().int().nonnegative(), minutes: z.number().int().positive(),
  })).min(1),
  // Bottles that count as "a bottle of water" for recipes that use one; the first is used first.
  waterItemIds: z.array(slug('item')).min(1),
  // Each turns up to maxBatch of `from` into as many `to` over a burning fire.
  recipes: z.array(z.object({
    id: slug('recipe'), name: z.string().min(1), from: slug('item'), to: slug('item'),
    maxBatch: z.number().int().positive(), minutes: z.number().int().positive(),
    tool: slug('item').nullable(), usesWater: z.boolean(),
  })).min(1),
});

// Crafting (M5, P-017): anywhere, no fire. Inputs are used up; the tool is kept.
export const recipeSchema = z.object({
  id: slug('recipe'),
  name: z.string().min(1),
  inputs: z.array(z.object({ itemId: slug('item'), count: z.number().int().positive() })).min(1),
  tool: slug('item').nullable(),
  minutes: z.number().int().positive(),
  output: z.object({ itemId: slug('item'), count: z.number().int().positive() }),
});

// Generated by scripts/geo/build-water.mjs. Coordinates are [lon, lat]. `river` marks flowing (clean) water.
export const waterSchema = z.object({
  areas: z.array(z.object({ river: z.boolean(), ring: z.array(z.tuple([lon, lat])).min(4) })),
  rivers: z.array(z.array(z.tuple([lon, lat])).min(2)),
  // Mapped wells: clean water (D-050).
  wells: z.array(z.tuple([lon, lat])),
});

// A kind of building on a town map, with its own search time, stock loss and loot (D-049, P-014).
export const buildingTypeSchema = z.object({
  id: slug('btype'),
  name: z.string().min(1),
  searchMinutes: z.number().int().positive(),
  torchSearchMinutes: z.number().int().positive(),
  depletionPerSearch: z.number().min(0).max(100),
  search: z.array(lootEntry).min(1),
});

// A town's map (D-049): buildings and water placed at real coordinates. The town's site point is its edge.
export const townSchema = z.object({
  siteId: slug('loc'),
  buildings: z.array(z.object({ id: slug('building'), typeId: slug('btype'), name: z.string().min(1), lat, lon })).min(1),
  // A well gives clean water, a tank unsafe water (D-044, D-050).
  water: z.array(z.object({ id: slug('waterpoint'), kind: z.enum(['well', 'tank']), name: z.string().min(1), lat, lon })),
  // Ways out besides the edge (D-054): leaving from one puts Prabu at that spot on the world map.
  ends: z.array(z.object({ id: slug('end'), name: z.string().min(1), lat, lon })),
});

// A lasting modifier on Prabu (D-061). `minutes: null` lasts until it is ended another way.
export const conditionSchema = z.object({
  id: slug('condition'),
  name: z.string().min(1),
  description: z.string().min(1),
  good: z.boolean().optional(),
  minutes: z.number().int().positive().nullable(),
  speedMultiplier: z.number().positive().optional(),
  // Applies while awake.
  restDrainMultiplier: z.number().positive().optional(),
  maxHealth: z.number().optional(),
  healthPerHour: z.number().optional(),
  searchTimeMultiplier: z.number().positive().optional(),
  // Multiplies damage he deals in a fight (Weak, D-061).
  damageMultiplier: z.number().positive().optional(),
  blocksHealing: z.boolean().optional(),
  curedBy: z.array(slug('item')).optional(),
  // Ends after one rest at least this long.
  endsAfterSleepMinutes: z.number().int().positive().optional(),
  // Ends after one rest at least this long at home or beside a fire.
  endsAfterShelteredRestMinutes: z.number().int().positive().optional(),
});

// One way to meet a choice's need; a choice can list several (any one will do).
const eventNeed = z.object({
  // All of these, in the pack or the weapon slot; items with charge need some left.
  items: z.array(slug('item')).optional(),
  // Any item of this kind.
  categories: z.array(z.enum(itemCategories)).optional(),
  weapon: z.boolean().optional(),
  night: z.boolean().optional(),
});

const eventOutcome = z.object({
  chance: z.number().min(0).max(1),
  text: z.string().min(1),
  health: z.number().optional(),
  food: z.number().optional(),
  water: z.number().optional(),
  rest: z.number().optional(),
  injure: z.boolean().optional(),
  ill: z.boolean().optional(),
  conditions: z.array(slug('condition')).optional(),
  minutes: z.number().int().positive().optional(),
  activity: z.enum(['work', 'travel', 'sleep']).optional(),
  // Each draw takes the first entry that hits; finds go into the pack, or on the ground if too heavy.
  loot: z.object({ draws: z.number().int().positive(), entries: z.array(lootEntry).min(1) }).optional(),
  // One more draw from the table of the building he is searching.
  extraFind: z.boolean().optional(),
  // Takes one item from the pack: the first of these items, or else of these kinds.
  lose: z.object({ items: z.array(slug('item')).optional(), categories: z.array(z.enum(itemCategories)).optional() }).optional(),
  stopTravel: z.boolean().optional(),
  // Starts a fight (M7). An ambush puts the enemies at Close and gives them the first round.
  fight: z.object({
    enemies: z.array(z.object({ enemyId: slug('enemy'), min: z.number().int().positive(), max: z.number().int().positive() })).min(1),
    ambush: z.boolean().optional(),
  }).optional(),
  // Reveals the nearest place he hasn't found yet.
  revealNearest: z.boolean().optional(),
});

export const eventSchema = z.object({
  id: slug('event'),
  title: z.string().min(1),
  text: z.string().min(1),
  on: z.array(z.enum(['travel', 'walk', 'search', 'rest', 'hunt'])).min(1),
  // Travel only: the ground most of the leg was on.
  ground: z.enum(['road', 'cross']).optional(),
  when: z.enum(['day', 'night']).optional(),
  // Only when moving in the dark without light (D-048).
  unlit: z.boolean().optional(),
  // Between these hours of the day, [from, to).
  hours: z.tuple([z.number().int().min(0).max(24), z.number().int().min(0).max(24)]).optional(),
  waterBelow: z.number().optional(),
  nearTownKm: z.number().positive().optional(),
  buildingTypes: z.array(slug('btype')).optional(),
  threat: z.boolean().optional(),
  weight: z.number().positive(),
  nightWeight: z.number().positive().optional(),
  // A single choice with an empty label resolves by itself: the card shows only what happened.
  choices: z.array(z.object({
    id: z.string().regex(/^[a-z0-9_]+$/),
    label: z.string(),
    tag: z.string().optional(),
    needs: z.array(eventNeed).optional(),
    outcomes: z.array(eventOutcome).min(1),
  })).min(1),
});

// Events (M6, D-059).
export const eventsSchema = z.object({
  travelChancePerLeg: z.object({ road: z.number().min(0).max(1), cross: z.number().min(0).max(1) }),
  searchChance: z.number().min(0).max(1),
  restChancePerHour: z.number().min(0).max(1),
  huntChance: z.number().min(0).max(1),
  unlitMultiplier: z.number().min(1),
  exhaustedThreatMultiplier: z.number().min(1),
  cooldownMinutes: z.number().int().nonnegative(),
  // Threat events at night leave this condition (D-061).
  nightThreatCondition: slug('condition'),
  events: z.array(eventSchema).min(1),
});

// An enemy type (D-064, D-066). Every loot entry rolls on its own.
export const enemySchema = z.object({
  id: slug('enemy'),
  name: z.string().min(1),
  hp: z.number().int().positive(),
  damage: z.tuple([z.number().int().nonnegative(), z.number().int().nonnegative()]),
  def: z.number(), spd: z.number(), acc: z.number(), dodge: z.number(), critRate: z.number(), critDamage: z.number(),
  // Bands it may start in, picked at random.
  start: z.array(z.enum(bands)).min(1),
  // melee: closes in, then attacks. archer: shoots from Mid or Far, steps back when Close.
  behaviour: z.enum(['melee', 'archer']),
  // A crit by this enemy may leave a condition (a dirty dog bite).
  critCondition: z.object({ conditionId: slug('condition'), chance: z.number().min(0).max(1) }).optional(),
  loot: z.array(lootEntry),
});

// Combat numbers (D-063, D-066).
export const combatSchema = z.object({
  unarmed: weaponProfile,
  dieSides: z.number().int().positive(),
  hitChance: z.tuple([z.number(), z.number()]),
  defCap: z.number().min(0).max(100),
  aim: z.object({ acc: z.number(), critRate: z.number() }),
  minutesPerRound: z.number().int().positive(),
  arrowRecovery: z.number().min(0).max(1),
  flee: z.object({
    base: z.number(), mid: z.number(), far: z.number(),
    hurtAtHealth: z.number(), hurt: z.number(), loadedOverKg: z.number(), loaded: z.number(),
    range: z.tuple([z.number(), z.number()]),
  }),
  // What each point of Luck adds (D-066).
  luck: z.object({ searchPercent: z.number(), hunting: z.number(), flee: z.number(), critRate: z.number() }),
});

// Generated by scripts/geo/build-town-streets.mjs: street lines per town, [lon, lat]; drawn only.
export const townStreetsSchema = z.record(z.string(), z.array(z.array(z.tuple([lon, lat])).min(2)));

